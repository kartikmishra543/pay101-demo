const page = window.location.pathname.replace(/^\/+|\/+$/g, '').replace(/\.html$/, '');
const introduction = Object.hasOwn(introductions, page) ? introductions[page] : null;
const heading = document.querySelector('h1');
const paragraph = heading && [...document.querySelectorAll('p')].find(node =>
  heading.compareDocumentPosition(node) & Node.DOCUMENT_POSITION_FOLLOWING
);
const originalContent = [heading, paragraph].map(node => node && [...node.childNodes]);

function getLanguage() {
  try {
    const saved = localStorage.getItem('pay101-language');
    return Object.hasOwn(PAY101_I18N, saved) ? saved : 'en';
  } catch {
    return 'en';
  }
}

function SubpageHeader() {
  const [language, setLanguage] = React.useState(getLanguage);

  React.useEffect(() => {
    // The body of the static page stays in English. Mark each localized region.
    document.documentElement.lang = 'en';
    target.lang = language;
    const translations = introduction && {ru: introduction.slice(0, 2), ar: introduction.slice(2)};
    [heading, paragraph].forEach((node, index) => {
      if (!node || !translations) return;
      if (translations[language]) {
        node.textContent = translations[language][index];
        node.lang = language;
        node.dir = language === 'ar' ? 'rtl' : 'ltr';
      } else {
        node.replaceChildren(...originalContent[index]);
        node.removeAttribute('lang');
        node.removeAttribute('dir');
      }
    });
  }, [language]);

  return <Pay101Header language={language} onLanguageChange={setLanguage}/>;
}

const target = document.getElementById('pay101-shared-header');
if (target) createRoot(target).render(<SubpageHeader/>);
